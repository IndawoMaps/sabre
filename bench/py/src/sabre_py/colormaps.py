def build_lut(lut: list[tuple[int, int, int]]) -> np.ndarray:
    """Convert 16-point LUT to a (256, 3) uint8 array via linear interpolation."""
    n = len(lut)
    arr = np.array(lut, dtype=np.float32)
    xs = np.linspace(0.0, 1.0, n)
    out_xs = np.linspace(0.0, 1.0, 256)
    # Use round() to match the Rust lerp() which calls .round() before u8 cast
    result = np.stack(
        [np.interp(out_xs, xs, arr[:, ch]) for ch in range(3)], axis=1
    )
    return np.round(result).clip(0, 255).astype(np.uint8)


_LUT_CACHE: dict[str, np.ndarray] = {}


def get_lut(name: str) -> np.ndarray:
    """Return the 256-entry (256, 3) uint8 LUT for the named colormap."""
    if name not in _LUT_CACHE:
        lut = COLORMAPS.get(name)
        if lut is None:
            raise ValueError(f"Unknown colormap: {name!r}. Available: {list(COLORMAPS)}")
        _LUT_CACHE[name] = build_lut(lut)
    return _LUT_CACHE[name]
